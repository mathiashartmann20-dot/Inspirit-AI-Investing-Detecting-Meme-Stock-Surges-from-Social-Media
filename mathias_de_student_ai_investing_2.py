def get_label(model: str, prompt: str, sample: str):
    response = client.responses.create(
        model=model,
        input= prompt + "\n" + sample
    )
    raw = response.output_text.capitalize()
    if raw in ("Positive", "Negative", "Neutral"):
        return raw
    for label in ("Positive", "Negative", "Neutral"):
        if label in raw:
            return label
    return "Failed to answer"

def judge_single(model: str, prompt: str, sample: str) -> str:
    for attempt in range(RETRY_LIMIT):
        try:
          return get_label(model, prompt, sample)
        except RateLimitError:
            wait = RETRY_DELAY * (attempt + 1)
            print(f"\n  [Rate limit] waiting {wait}s before retry {attempt+1}...")
            time.sleep(wait)
        except APIError as e:
            print(f"\n  [API error] {e}. Retry {attempt+1}/{RETRY_LIMIT}")
            time.sleep(RETRY_DELAY)
        except Exception as e:
            # At the very least capture the general error.
            print(f"An error occurred: {e}")

    return None

def run_judge(model: str, prompt: str, texts: list[str], desc: str = "GPT judge") -> list[str]:
    """Run judge over a list of texts with a progress bar."""
    labels = []
    for sample in tqdm(texts, desc=f"  {desc}"):
        labels.append(judge_single(model, prompt, sample))
    return labels

def run_few_shot(original_prompt: str, texts: list[str], examples: list[dict], desc: str) -> list[str]:
    preds = []
    for text in tqdm(texts, desc=f"  {desc}"):
        prompt = original_prompt + "\n" + build_few_shot_prompt(examples, text)
        preds.append(judge_single(model=MODEL, prompt=prompt, sample=text))
    return preds

