def get_reviews_for_topic(topic, num_reviews):
    """Get relevant reviews for a topic via semantic search, with fallback."""
    query = topic.strip().lower()
    try:
        if 'review_embeddings' in globals() and review_embeddings is not None:
            top_results = find_top_reviews(query, review_embeddings, yelp, top_n=num_reviews)
            return [result[1] for result in top_results]
    except Exception as e:
        print(f"⚠️ Semantic search error: {e}")
    return yelp['text'].head(num_reviews).tolist()


def call_openai_model(model, messages, max_tokens):
    """Call OpenAI models with GPT-5 support (no temperature)."""
    try:
        reasoning_models = {"gpt-5", "gpt-5-mini", "gpt-5-nano", "o3-mini"}

        if model in reasoning_models:
            system_text = ""
            user_parts = []
            for msg in messages:
                if msg.get("role") == "system":
                    system_text = msg.get("content", "")
                elif msg.get("role") == "user":
                    user_parts.append(msg.get("content", ""))

            response = client.responses.create(
                model=model,
                instructions=system_text if system_text else None,
                input="\n\n".join(user_parts),
                max_output_tokens=max_tokens,
                reasoning={"effort": "low"},
            )
            text = (getattr(response, "output_text", None) or "").strip()
            return text if text else "No response generated. Try increasing max tokens."

        # Non-GPT-5 fallback
        response = client.chat.completions.create(
            model=model,
            messages=messages,
            max_completion_tokens=max_tokens,
        )
        content = response.choices[0].message.content
        return (content or "").strip()

    except Exception as e:
        return f"⚠️ Error: {str(e)}"


def run_single_analysis(model, max_tokens, system_prompt, user_prompt, topic, num_reviews):
    """Run one analysis and return a result dict."""
    reviews_sample = get_reviews_for_topic(topic, num_reviews)
    reviews_text = "\n".join([f"• {r}" for r in reviews_sample])

    if not reviews_text.strip():
        return {'success': False, 'error': "No reviews found."}

    try:
        sys_p = system_prompt.strip() or "You are an expert restaurant consultant analyzing customer reviews."
        usr_p = user_prompt.strip() or "Analyze these reviews about {topic}:\n\n{reviews_text}\n\nProvide 3 actionable tips."
        formatted = usr_p.replace("{topic}", topic).replace("{reviews_text}", reviews_text)

        messages = [
            {"role": "system", "content": sys_p},
            {"role": "user", "content": formatted},
        ]
        result = call_openai_model(model, messages, max_tokens)
        return {
            'success': True,
            'summary': result,
            'topic': topic,
            'num_reviews': len(reviews_sample),
            'model': model,
            'max_tokens': max_tokens,
        }
    except Exception as e:
        return {'success': False, 'error': str(e)}


