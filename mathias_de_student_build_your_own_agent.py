"""## 2.2. Custom Tools with `@function_tool`

Built-in tools like `WebSearchTool` are powerful, but sometimes you need something custom. The `@function_tool` decorator turns any Python function into a tool your agent can call.

The agent reads your **function name**, **docstring**, and **type hints** to understand what the tool does and when to use it. Clear docstrings = smarter tool use.

For example, the custom tool below fetches the current weather for any city using a free weather API - no API key required. Here's how this tool was created:

> 💡 *This is just one example - any Python function can become a tool. It can call any API or return any output your agent needs.*
"""

# Example custom tool - gives the agent the ability to look up current weather for any city.
# Uses Open-Meteo, a free weather API (no API key required).
#
# How it works, in 2 steps:
#   1️⃣  City name → coordinates (latitude/longitude)
#   2️⃣  Coordinates → current weather

import requests  # Python library for calling APIs over HTTP

@function_tool
def get_weather(city: str) -> str:
    """Get the current weather for a city.

    Args:
        city: The name of the city (e.g., 'Tokyo', 'San Francisco').
    """
    # 1️⃣  City name → coordinates ─────────────────────────────────
    # Call the geocoding API. .json() turns the response into a Python dict.
    geo_response = requests.get(
        "https://geocoding-api.open-meteo.com/v1/search",
        params={"name": city, "count": 1},
    ).json()

    # The API returns a list of matches under "results". Bail out if empty.
    results = geo_response.get("results")
    if not results:
        return f"Couldn't find a location named '{city}'."

    # Take the first (best) match and pull out what we need
    location = results[0]
    lat = location["latitude"]
    lon = location["longitude"]
    name = location["name"]

    # 2️⃣  Coordinates → current weather ───────────────────────────
    weather_response = requests.get(
        "https://api.open-meteo.com/v1/forecast",
        params={"latitude": lat, "longitude": lon, "current": "temperature_2m,wind_speed_10m"},
    ).json()

    current = weather_response.get("current")
    if not current:
        return f"Couldn't fetch weather for {name}."

    temp_c = current["temperature_2m"]
    wind = current["wind_speed_10m"]

    # Return a plain-English string - this is what the agent reads and weaves into its reply
    return f"The current weather in {name} is {temp_c}°C with wind at {wind} km/h."

# Confirm the tool is registered (the agent reads name + description to know when to call it)
print("Tool name:", get_weather.name)
print("Tool description:", get_weather.description)

"""To equip our agent with the tool, we can add it to the agent's `tools` list. For better results, we can also add a brief description and guidance on how to use them in the agent's `instructions`.

(Since `get_weather` is now a tool object as printed above, it doesn't need parentheses here.)
"""

