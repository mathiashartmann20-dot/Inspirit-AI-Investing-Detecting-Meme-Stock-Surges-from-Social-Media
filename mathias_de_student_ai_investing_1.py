#@title Run to create a helper function for running FinVADER on our dataset

# Both financial lexicons enabled. This is FinVADER's key upgrade over VADER.
USE_SENTIBIGNOMICS = True   # SentiBigNomics: ~7,300 financial sentiment terms
USE_HENRY          = True   # Henry's word list: classic financial lexicon

def finvader_label(text: str) -> str:
    score = finvader(
        text,
        use_sentibignomics=USE_SENTIBIGNOMICS,
        use_henry=USE_HENRY,
        indicator="compound",
    )
    if score >= COMPOUND_POS:
        return "Positive"
    elif score <= COMPOUND_NEG:
        return "Negative"
    else:
        return "Neutral"

