def plot_distribution(df: pd.DataFrame, pred_col: str, true_col: str,
                      dataset_name: str) -> None:
    """Side-by-side bar charts: predicted vs. ground-truth label distribution."""
    fig, axes = plt.subplots(1, 2, figsize=(12, 4))
    fig.suptitle(f"{dataset_name} — Label Distribution", fontsize=14, fontweight="bold")

    for ax, col, title in zip(axes,
                               [pred_col, true_col],
                               ["VADER Predictions", "Ground Truth"]):
        counts = df[col].value_counts()
        ax.bar(counts.index, counts.values,
               color=["#2ecc71", "#e74c3c", "#95a5a6"][:len(counts)])
        ax.set_title(title)
        ax.set_xlabel("Sentiment")
        ax.set_ylabel("Count")
        for i, v in enumerate(counts.values):
            ax.text(i, v + max(counts.values) * 0.01, str(v),
                    ha="center", fontsize=10)

    plt.tight_layout()
    plt.show()


def plot_confusion(df: pd.DataFrame, pred_col: str, true_col: str,
                   dataset_name: str, labels: list) -> None:
    """Normalised confusion matrix heatmap."""
    cm = confusion_matrix(df[true_col], df[pred_col], labels=labels, normalize="true")
    fig, ax = plt.subplots(figsize=(6, 5))
    sns.heatmap(cm, annot=True, fmt=".2f", cmap="Blues",
                xticklabels=labels, yticklabels=labels, ax=ax)
    ax.set_title(f"{dataset_name} — Confusion Matrix (normalised)", fontweight="bold")
    ax.set_xlabel("Predicted")
    ax.set_ylabel("Ground Truth")
    plt.tight_layout()
    plt.show()


def evaluate(df: pd.DataFrame, pred_col: str, true_col: str,
             dataset_name: str, labels: list) -> None:
    """Print accuracy + full classification report."""
    acc = accuracy_score(df[true_col], df[pred_col])
    print(f"\n{'='*60}")
    print(f" {dataset_name}")
    print(f"{'='*60}")
    print(f" Accuracy : {acc:.4f}  ({acc*100:.2f}%)")
    print(f"\n Classification Report:\n")
    print(classification_report(df[true_col], df[pred_col],
                                 labels=labels, zero_division=0))
    plot_distribution(df, pred_col, true_col, dataset_name)
    plot_confusion(df, pred_col, true_col, dataset_name, labels)

